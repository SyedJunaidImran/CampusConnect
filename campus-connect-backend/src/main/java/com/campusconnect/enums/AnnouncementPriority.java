package com.campusconnect.enums;

/**
 * Defines priority levels for announcements in CampusConnect.
 *
 * - GENERAL: Standard update or informational notice.
 * - IMPORTANT: Notable deadline, scheduling change, or policy update.
 * - URGENT: High-priority immediate alert (e.g., campus closure, exam schedule release).
 */
public enum AnnouncementPriority {
    GENERAL,
    IMPORTANT,
    URGENT
}
